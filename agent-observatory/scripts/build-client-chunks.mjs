// Regenerates server/generated/ui-chunk.txt and shared/generated/ui-chunk-manifest.ts
// exactly the way the daemon's plugin compiler (server/compiler.js) does, for hosts
// building outside the maintainer's repository. Run from the plugin directory:
//   node scripts/build-client-chunks.mjs
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, realpathSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const result = await build({
  entryPoints: [realpathSync(join(root, "ui-chunk.client.tsx"))], bundle: true, format: "cjs", jsx: "automatic",
  loader: { ".svg": "text" }, platform: "neutral", target: "es2020", mainFields: ["module", "main"],
  supported: { "async-await": false },
  external: ["@getpaseo/plugin", "@getpaseo/plugin/server", "@getpaseo/plugin/server/provider", "@getpaseo/plugin/server/acp",
    "@getpaseo/plugin/client", "@getpaseo/plugin/client/ui", "@getpaseo/plugin/client/react-native",
    "@tanstack/react-query", "react", "react/jsx-runtime", "react-native", "zod"],
  metafile: true, logLevel: "silent", treeShaking: true, write: false,
});
let output = result.outputFiles[0].text;
// Hermes evaluates esbuild's lazy CommonJS interop getters from a string with the final
// loop binding; plugin bundles run once and need no live bindings from host modules.
output = output.replaceAll("get: () => from[key]", "value: from[key]");
const wrapped = `(function(require) {\nconst module = { exports: {} };\nconst exports = module.exports;\n${output}\nreturn module.exports;\n})`;
// Never build on a drifted base: the committed artifact must match its recorded hash.
const oldTxt = readFileSync(join(root, "server", "generated", "ui-chunk.txt"), "utf8");
const recorded = /hash:"([0-9a-f]{16})"/.exec(readFileSync(join(root, "shared", "generated", "ui-chunk-manifest.ts"), "utf8"))?.[1];
const oldHash = createHash("sha256").update(oldTxt).digest("hex").slice(0, 16);
if (oldHash !== recorded) throw new Error(`old artifact hash ${oldHash} != manifest ${recorded}; regenerate from a clean checkout`);
writeFileSync(join(root, "server", "generated", "ui-chunk.txt"), wrapped);
const hash = createHash("sha256").update(wrapped).digest("hex").slice(0, 16);
writeFileSync(join(root, "shared", "generated", "ui-chunk-manifest.ts"),
  `// Generated by scripts/build-client-chunks.mjs; do not edit.\nexport const UI_CHUNK = {name:"ui",hash:"${hash}",api:1,bytes:${Buffer.byteLength(wrapped)}} as const;\n`);
console.log(`ui chunk regenerated: ${Buffer.byteLength(wrapped)} bytes, hash ${hash} (was ${oldHash})`);
